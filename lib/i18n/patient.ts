/**
 * Copy for the signed-in patient app (Home, Check-in, Smart Journal, Reports,
 * Settings, the welcome and the first conversation). Kept apart from the marketing
 * dictionary so the two can grow independently. `ar` is typed against `en`: a missing
 * key fails the build. Placeholders use `{name}` — fill them with `fill()`.
 */

/**
 * The crisis wording for what there is to show: "You can also reach:" only leads into a list that exists.
 * Without configured emergency numbers it would end on a dangling colon, in the one message that must be clear.
 */
export function crisisBodyFor(crisis: { body: string; bodyShort: string }, resources?: readonly string[]): string {
  return resources && resources.length > 0 ? crisis.body : crisis.bodyShort;
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

